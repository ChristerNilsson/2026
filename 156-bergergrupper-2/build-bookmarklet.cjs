'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const style = read('dist/style.css').replace(/<\/style/gi, '<\\/style');
const app = read('dist/app.js').replace(/<\/script/gi, '<\\/script');
const html = read('dist/index.html')
  .replace('<link rel="stylesheet" href="style.css">', () => '<style>' + style + '</style>')
  .replace('<script src="bookmarklet.js" defer></script>', '')
  .replace('<script src="app.js" defer></script>', '')
  .replace('</body>', () => '<script>Object.assign(window,__BERGER_CONFIG__);</script><script>' + app + '</script></body>');

function start(template) {
  const sourceUrl = window.BERGER_BOOT?.sourceUrl || location.href;
  const parsed = new URL(sourceUrl);
  const value = Number(parsed.searchParams.get('round'));
  const round = Number.isInteger(value) && value >= 1 && value <= 100 ? value : 1;
  const config = JSON.stringify({BERGER_LIVE:true, BERGER_ROUND:round, BERGER_SOURCE_URL:sourceUrl}).replace(/</g, '\\u003c');
  document.open();
  document.write(template.replace('__BERGER_CONFIG__', () => config));
  document.close();
}
fs.writeFileSync(path.join(root, 'dist/bergergrupper.js'), '// Generated by node build-bookmarklet.cjs.\n(' + start.toString() + ')(' + JSON.stringify(html) + ');\n');

// The small, stable bookmark fetches the latest bundle from the public GitHub repo.
const codeUrl = 'https://raw.githubusercontent.com/ChristerNilsson/2026/main/156-bergergrupper-2/dist/bergergrupper.js';
const loader = `javascript:(()=>{if(location.hostname!=='member.schack.se'||location.protocol!=='https:'){alert('Kör bokmärket på member.schack.se');return}const u=location.href,w=open('','_blank');if(!w){alert('Tillåt popup-fönster för member.schack.se');return}w.document.body.textContent='Hämtar bordslistan från GitHub…';fetch('${codeUrl}?v='+Date.now(),{cache:'no-store'}).then(r=>{if(!r.ok)throw Error('GitHub HTTP '+r.status);return r.text()}).then(c=>{if(w.closed)return;w.BERGER_BOOT={sourceUrl:u};const s=w.document.createElement('script');s.textContent=c;w.document.head.append(s)}).catch(e=>{if(!w.closed)w.document.body.textContent='Kunde inte hämta bordslistan: '+e.message})})();void 0;`;
fs.writeFileSync(path.join(root, 'dist/bookmarklet.js'), '// Generated by node build-bookmarklet.cjs.\nconst BOOKMARKLET_URL = ' + JSON.stringify(loader) + ';\n');
fs.writeFileSync(path.join(root, 'dist/bergergrupper-bookmarklet.txt'), loader + '\n');
const readme = read('README.md').replace(/<!-- BOOKMARKLET -->[\s\S]*?<!-- \/BOOKMARKLET -->/, () => '<!-- BOOKMARKLET -->\n```javascript\n' + loader + '\n```\n<!-- /BOOKMARKLET -->');
fs.writeFileSync(path.join(root, 'README.md'), readme);
console.log('Built GitHub bundle and loader (' + loader.length + ' characters).');
