'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const write = (file, value) => fs.writeFileSync(path.join(root, file), value);
const style = read('dist/style.css').replace(/<\/style/gi, '<\\/style');
const app = read('dist/app.js').replace(/<\/script/gi, '<\\/script');
const boardHtml = read('dist/index.html');
const standingsHeaders = ['Grupp', 'Plac.', 'Namn', 'Klubb', 'Elo', 'Sp', 'Poäng', 'Kv.p'];
const standingsHtml = boardHtml
  .replace('<title>Bergergrupper</title>', '<title>Bergergrupper · Ställning</title><script>window.BERGER_VIEW="standings";</script>')
  .replace('src="bookmarklet.js"', 'src="standings-bookmarklet.js"')
  .replace('<body>', '<body class="standings">')
  .replace('Alla bord. En överblick.', 'Alla grupper. En ställning.')
  .replace(/♜ Bergergrupper/g, '♜ bergergrupper-standings')
  .replace(/<div><label for="round">Rond<\/label><div class="roundpicker">[\s\S]*?<\/div><\/div>/, '<div>Aktuell ställning</div>')
  .replace('Skriv ut bordslista', 'Skriv ut ställning')
  .replace(' · Bordslista ', ' · Ställning ')
  .replace(/<thead>[\s\S]*?<\/thead>/, '<thead><tr>' + standingsHeaders.map((label, i) => '<th scope="col"' + (i >= 4 ? ' class="numeric"' : '') + '>' + label + '</th>').join('') + '</tr></thead>')
  .replace('<p>Om du har det gamla bokmärket: ersätt det med det här. Det nya öppnar bordslistan direkt.</p>', '<p>Skapa ett separat bokmärke med namnet bergergrupper-standings.</p>');
write('dist/standings.html', standingsHtml);

function start(template, view) {
  const sourceUrl = window.BERGER_BOOT?.sourceUrl || location.href;
  const parsed = new URL(sourceUrl);
  const value = Number(parsed.searchParams.get('round'));
  const round = Number.isInteger(value) && value >= 1 && value <= 100 ? value : 1;
  const config = JSON.stringify({BERGER_LIVE:true, BERGER_ROUND:round, BERGER_SOURCE_URL:sourceUrl, BERGER_VIEW:view}).replace(/</g, '\\u003c');
  document.open();
  document.write(template.replace('__BERGER_CONFIG__', () => config));
  document.close();
}
let readme = read('README.md');
for (const view of ['boards', 'standings']) {
  const standings = view === 'standings';
  const name = standings ? 'bergergrupper-standings' : 'bergergrupper';
  const noun = standings ? 'ställningen' : 'bordslistan';
  const template = (standings ? standingsHtml : boardHtml)
    .replace('<link rel="stylesheet" href="style.css">', () => '<style>' + style + '</style>')
    .replace('<script>window.BERGER_VIEW="standings";</script>', '')
    .replace(/<script src="(?:standings-)?bookmarklet.js" defer><\/script>/, '')
    .replace('<script src="app.js" defer></script>', '')
    .replace('</body>', () => '<script>Object.assign(window,__BERGER_CONFIG__);</script><script>' + app + '</script></body>');
  write('dist/' + name + '.js', '// Generated by node build-bookmarklet.cjs.\n(' + start.toString() + ')(' + JSON.stringify(template) + ',' + JSON.stringify(view) + ');\n');
  const codeUrl = 'https://raw.githubusercontent.com/ChristerNilsson/2026/main/156-bergergrupper-2/dist/' + name + '.js';
  const loader = `javascript:(()=>{if(location.hostname!=='member.schack.se'||location.protocol!=='https:'){alert('Kör bokmärket på member.schack.se');return}const u=location.href,w=open('','_blank');if(!w){alert('Tillåt popup-fönster för member.schack.se');return}w.document.body.textContent='Hämtar ${noun} från GitHub…';fetch('${codeUrl}?v='+Date.now(),{cache:'no-store'}).then(r=>{if(!r.ok)throw Error('GitHub HTTP '+r.status);return r.text()}).then(c=>{if(w.closed)return;w.BERGER_BOOT={sourceUrl:u};const s=w.document.createElement('script');s.textContent=c;w.document.head.append(s)}).catch(e=>{if(!w.closed)w.document.body.textContent='Kunde inte hämta ${noun}: '+e.message})})();void 0;`;
  write('dist/' + (standings ? 'standings-' : '') + 'bookmarklet.js', '// Generated by node build-bookmarklet.cjs.\nconst BOOKMARKLET_URL = ' + JSON.stringify(loader) + ';\n');
  write('dist/' + name + '-bookmarklet.txt', loader + '\n');
  const marker = standings ? 'STANDINGS_BOOKMARKLET' : 'BOOKMARKLET';
  readme = readme.replace(new RegExp('<!-- ' + marker + ' -->[\\s\\S]*?<!-- /' + marker + ' -->'), () => '<!-- ' + marker + ' -->\n```javascript\n' + loader + '\n```\n<!-- /' + marker + ' -->');
}
write('README.md', readme);
console.log('Built bergergrupper and bergergrupper-standings bundles and GitHub loaders.');
